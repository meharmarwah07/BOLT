"""One-off script: precompute the real Check 1 (300 train seeds) result for a
fixed set of (grip, accel) inputs, so demo/app.py can show them instantly
instead of re-running a ~1-2 minute live simulation on every page load.

Run once, by hand, from the repo root:
    PYTHONPATH=. venv/bin/python3 demo_data/gen_check1_300_precomputed.py

Writes demo_data/check1_300_precomputed.json. Every number in it comes from
a real pipeline/check1.py check1() call on real train seeds 0-299 -- nothing
here is estimated or hand-typed.
"""
import datetime as dt
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PIPELINE_DIR = os.path.join(ROOT, "pipeline")
SIM_DIR = os.path.join(ROOT, "sim")
LLM_DIR = os.path.join(ROOT, "llm")
for _p in (ROOT, PIPELINE_DIR, SIM_DIR, LLM_DIR):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import check1 as check1_mod  # pipeline/check1.py
from rules.schema import Rule

# The 5 inputs documented for the demo (see docs/ and this repo's own prior
# measurement session): the three real revision-2 accepted policies, plus
# two deliberately-failing points (one that crushes, one with too many
# drops), all at 300 train seeds -- the revision-2 gate.
INPUTS = [(20.0, 1.0), (20.0, 0.5), (21.0, 0.5), (25.0, 0.5), (12.0, 1.0)]
TRAIN_SEEDS = range(300)


def _outcome_to_dict(grip, accel, outcome):
    rec = outcome.record
    return {
        "grip_force_min_n": grip,
        "carry_accel_max_ms2": accel,
        "passed": outcome.passed,
        "n_trials": outcome.n_trials,
        "drops_before": rec.drops_before,
        "drops_after": rec.drops_after,
        "crush_count": rec.crush_count,
        "other_classes_unchanged": rec.other_classes_unchanged,
        "drop_rate_after": outcome.drop_rate_after,
        "drop_rate_after_ci95": list(outcome.drop_rate_after_ci95),
        "combined_failure_rate": outcome.combined_failure_rate,
        "combined_failure_ci95": list(outcome.combined_failure_ci95) if outcome.combined_failure_ci95 else None,
        "reasons": outcome.reasons,
    }


if __name__ == "__main__":
    results = []
    for grip, accel in INPUTS:
        rule = Rule(
            rule_id=f"r_precomputed_{grip:.2f}_{accel:.2f}".replace(".", "p"),
            object_class="glass_jar",
            grip_force_min_n=grip,
            carry_accel_max_ms2=accel,
            proposed_by="demo-precompute",
            created_at=dt.datetime.now(dt.timezone.utc),
            rationale=f"Precomputed demo entry: grip_force_min_n={grip} N, carry_accel_max_ms2={accel} m/s^2 for glass_jar.",
            source_report_ids=["demo-precomputed-check1-300"],
        )
        t0 = dt.datetime.now()
        outcome = check1_mod.check1(rule, TRAIN_SEEDS)
        elapsed_s = (dt.datetime.now() - t0).total_seconds()
        print(f"grip={grip} accel={accel} passed={outcome.passed} elapsed={elapsed_s:.1f}s")
        results.append(_outcome_to_dict(grip, accel, outcome))

    out = {
        "_comment": (
            "Generated by a real pipeline/check1.py check1() call on real train seeds 0-299 "
            "(see demo_data/gen_check1_300_precomputed.py for the exact script). Not estimated, "
            "not hand-typed. Labeled 'precomputed' wherever shown in the app -- it is a cached "
            "result, not a live run."
        ),
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "train_seeds": "0-299",
        "object_class": "glass_jar",
        "entries": results,
    }
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "check1_300_precomputed.json")
    with open(out_path, "w") as f:
        json.dump(out, f, indent=2)
    print(f"wrote {out_path}")
